        document.addEventListener('DOMContentLoaded', function() {
            const loginForm = document.getElementById('loginForm');
            const loginEmailInput = document.getElementById('loginEmail');
            const loginPasswordInput = document.getElementById('loginPassword');
            const loginMessageDiv = document.getElementById('loginMessage');
            const registerButton = document.getElementById('registerButton');
            const registerMessageDiv = document.getElementById('registerMessage');

            // Función para mostrar mensajes de error o éxito
            function displayMessage(element, message, type) {
                element.textContent = message;
                element.className = `form-message ${type}`;
                element.style.display = 'block'; // Asegurar que el mensaje se muestre
            }

            // Validación del formulario de inicio de sesión y envío a PHP
            loginForm.addEventListener('submit', function(event) {
                event.preventDefault(); // Evitar el envío por defecto

                let isValid = true;

                if (!loginEmailInput.value.trim()) {
                    displayMessage(loginMessageDiv, 'Por favor, ingrese su correo electrónico.', 'error');
                    isValid = false;
                } else if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(loginEmailInput.value)) {
                    displayMessage(loginMessageDiv, 'Por favor, ingrese un correo electrónico válido.', 'error');
                    isValid = false;
                } else {
                    displayMessage(loginMessageDiv, '', ''); // Limpiar mensaje si es válido
                }

                if (!loginPasswordInput.value) {
                    displayMessage(loginMessageDiv, 'Por favor, ingrese su contraseña.', 'error');
                    isValid = false;
                } else {
                    displayMessage(loginMessageDiv, '', ''); // Limpiar mensaje si es válida
                }

                if (isValid) {
                    const formData = new FormData(loginForm);

                    fetch('login.php', {
                        method: 'POST',
                        body: formData
                    })
                    .then(response => response.text())
                    .then(data => {
                        if (data === 'success') {
                            displayMessage(loginMessageDiv, '¡Inicio de sesión exitoso!', 'success');
                            loginForm.style.display = 'none'; // Ocultar el formulario de inicio de sesión
                            // Aquí podrías redirigir al usuario a otra página o realizar otras acciones
                            window.location.href = 'pagina_principal.php'; // Redirigir a la página principal
                        } else {
                            displayMessage(loginMessageDiv, 'Error al iniciar sesión: ' + data, 'error');
                        }
                    })
                    .catch(error => {
                        displayMessage(loginMessageDiv, 'Hubo un error de conexión.', 'error');
                        console.error('Error:', error);
                    });
                }
            });

            // Lógica para el botón de "Registrar" (sin cambios)
            if (registerButton) {
                registerButton.addEventListener('click', function() {
                    displayMessage(registerMessageDiv, 'Redirigiendo a la página de registro...', 'info');
